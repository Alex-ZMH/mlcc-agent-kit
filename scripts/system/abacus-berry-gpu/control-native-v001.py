"""Control the in-situ candidate task with the existing SiteRunner.

Invoked through ssh v100. This file only submits/queries Slurm and saves task
bookkeeping; it does not perform numerical work or parse scientific results.
"""
import argparse
import json
from pathlib import Path
import subprocess

from mlcc.site_runner import SiteConfig, SiteRunner
from mlcc.tasks import load_task, save_task

WORKSPACE = Path('/home/v100/projects/mlcc/development/0.15.0/project/workspace')
SITE = WORKSPACE / 'configs/berry-gpu-native-v001/site.v100-berry-gpu-v001.json'
TASK = WORKSPACE / 'tasks/p5-czo-berry-gdir1-gpu-patched-v001/task.json'


def same_host_control(command, **kwargs):
    # The caller has already reached v100 through SSH. Run only the shell
    # control command that SiteRunner would otherwise send to this same host.
    if command[:2] != ['ssh', 'v100'] or len(command) != 3:
        raise ValueError(f'Unexpected control invocation: {command}')
    return subprocess.run(['bash', '-c', command[2]], **kwargs)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('action', choices=['bind-reference', 'submit', 'query'])
    args = parser.parse_args()
    task = load_task(TASK)
    runner = SiteRunner(SiteConfig.from_file(SITE), execute=same_host_control)
    if args.action == 'bind-reference':
        if task.scheduler_job_id is not None or task.data.get('submission_attempt_started_at'):
            raise ValueError('Dependency binding is only allowed before first submission')
        reference = task.data['berry']['source_reference_task_file']
        source_id = task.data['berry']['source_reference_task_id']
        for requirement in task.data['required_results']:
            if requirement['task_id'] == source_id:
                requirement['task_file'] = reference
        task.record_event('bind_external_reference', task_file=reference,
                          reason='reviewed cross-workspace preflight fix; no native submission had occurred')
        save_task(task)
        result = task.data
    elif args.action == 'submit':
        if task.data['status'] == 'prepared':
            for name in task.data['transfer_paths']:
                if not (TASK.parent / name).is_file():
                    raise FileNotFoundError(TASK.parent / name)
            task.set(status='transferred', transfer_mode='materialized_on_execution_host')
            task.record_event('in_situ_stage', status='transferred',
                              evidence='inputs generated by the recorded Slurm input-check job',
                              control_transport='caller ssh v100; SiteRunner invokes local Slurm client')
            save_task(task)
        elif task.data['status'] != 'transferred':
            raise ValueError('Submit requires the reviewed staged task')
        result = runner.submit(task)
    else:
        result = runner.query(task)
    print(json.dumps({key: result.get(key) for key in
                      ('task_id', 'status', 'scheduler_job_id', 'scheduler_state', 'exit_code')}, indent=2))


if __name__ == '__main__':
    main()
